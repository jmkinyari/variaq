import Link from "next/link";
import { notFound } from "next/navigation";
import db from "@/lib/db";
import "@/styles/ai.css";
import { requireWorkspace, can } from "@/lib/auth";
import PageHead from "@/components/PageHead";
import Flash from "@/components/Flash";
import Submit from "@/components/Submit";
import { TEMPLATES, reportHtml } from "@/lib/ai/assistant";
import { formatDateTime } from "@/lib/dates";
import { setVisibility, createShareLink, revokeShareLink, deleteReport } from "../../actions";
export const metadata = { title: "AI report" };

export default async function AiReportPage({ params, searchParams }) {
  const { ws, user } = await requireWorkspace(params.ws);
  const r = await db.get("SELECT r.*, u.name author FROM ai_reports r LEFT JOIN users u ON u.id = r.created_by WHERE r.id = ? AND r.workspace_id = ?", [params.id, ws.id]);
  if (!r || (r.visibility === "PRIVATE" && r.created_by !== user.id)) notFound();
  const mine = r.created_by === user.id || can(ws.role, "admin");
  const raw = `/app/${ws.slug}/ai/reports/${r.id}/raw`;
  const appUrl = process.env.APP_URL || "http://localhost:3000";
  const linkActive = r.share_expires_at && r.share_expires_at > db.now();
  const H = () => <><input type="hidden" name="slug" value={ws.slug} /><input type="hidden" name="id" value={r.id} /></>;
  return (
    <>
      <PageHead title={r.title} crumbs={<Link href={`/app/${ws.slug}/ai`}>← Variaq AI</Link>}
        desc={`${TEMPLATES[r.template]?.label || r.template}${r.period_from ? ` · ${r.period_from} – ${r.period_to}` : ""} · generated by ${r.author} on ${formatDateTime(r.created_at)} with ${r.model}`}>
        <a className="btn" href={raw} target="_blank" rel="noopener">Open / print</a>
        <a className="btn" href={`${raw}?download=1`}>Download HTML</a>
      </PageHead>
      <Flash searchParams={searchParams} />
      {searchParams.link && <div className="alert success">Share this read-only link (it's shown only once; anyone with it can view the report until it expires):
        <input readOnly value={`${appUrl}/r/${searchParams.link}`} style={{ marginTop: ".5rem" }} /></div>}

      <div className="ai-report-actions card">
        <div className="row between" style={{ flexWrap: "wrap", gap: ".6rem" }}>
          <div className="small">
            Visibility: <strong>{r.visibility === "TEAM" ? "everyone in this workspace" : "only you"}</strong>
            {linkActive ? <> · External link active until {formatDateTime(r.share_expires_at)}</> : null}
          </div>
          {mine && <div className="row" style={{ gap: ".4rem" }}>
            <form action={setVisibility}><H /><input type="hidden" name="visibility" value={r.visibility === "TEAM" ? "PRIVATE" : "TEAM"} /><Submit className="btn sm">{r.visibility === "TEAM" ? "Make private" : "Share with team"}</Submit></form>
            {can(ws.role, "data.edit") && (linkActive
              ? <form action={revokeShareLink}><H /><Submit className="btn sm">Revoke link</Submit></form>
              : <form action={createShareLink} className="row" style={{ gap: 4 }}><H /><select name="days" defaultValue="7" style={{ width: "auto" }} aria-label="Link expiry"><option value="1">1 day</option><option value="7">7 days</option><option value="30">30 days</option></select><Submit className="btn sm">Create share link</Submit></form>)}
            <form action={deleteReport}><H /><Submit className="btn sm danger" confirm="Delete this report?">Delete</Submit></form>
          </div>}
        </div>
      </div>
      {r.instructions && <p className="small muted">Instructions: {r.instructions}</p>}
      {/* Sanitised HTML in a fully sandboxed frame (no scripts, opaque origin). */}
      <iframe className="ai-report-frame" srcDoc={await reportHtml(ws, r)} title={r.title} sandbox="" />
    </>
  );
}

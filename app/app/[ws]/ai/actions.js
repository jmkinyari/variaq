/** Approve/reject a proposed action. Creating tasks needs edit rights; reports can be generated by anyone with AI access. */
export async function decide(slug, id, approve) {
  const { ws, user } = await requireWorkspace(slug);
  const p = await db.get("SELECT type FROM ai_actions WHERE id = ? AND workspace_id = ?", [String(id), ws.id]);
  if (!p) return { error: "Proposal not found." };
  if (approve && p.type === "CREATE_TASK" && !can(ws.role, "data.edit")) return { error: "Your role can't create tasks. Ask an accountant or admin to approve it." };
  if (approve && p.type === "GENERATE_REPORT" && !hit("heavy", `ai-report|${ws.id}`).ok) return { error: "Too many reports being generated. Wait a minute." };
  return decideProposal({ ws, user, id: String(id), approve: !!approve });
}

export async function createReport(formData) {
  const slug = String(formData.get("slug"));
  const { ws, user } = await requireWorkspace(slug);
  if (!hit("heavy", `ai-report|${ws.id}`).ok) back(`/app/${slug}/ai`, { err: "Too many reports being generated. Wait a minute." });
  const from = String(formData.get("from") || ""), to = String(formData.get("to") || "");
  const r = await generateReport({
    ws, user, template: String(formData.get("template") || "MANAGEMENT"), title: String(formData.get("title") || "").trim(),
    periodFrom: /^\d{4}-\d{2}-\d{2}$/.test(from) ? from : null, periodTo: /^\d{4}-\d{2}-\d{2}$/.test(to) ? to : null,
    instructions: String(formData.get("instructions") || "").trim(),
  });
  if (r.error) back(`/app/${slug}/ai`, { err: r.error });
  redirect(`/app/${slug}/ai/reports/${r.id}?ok=${encodeURIComponent("Report generated. Review it, then share it with your team or by link.")}`);
}

async function ownReport(formData, { needEdit = true } = {}) {
  const slug = String(formData.get("slug"));
  const { ws, user } = await requireWorkspace(slug);
  const rep = await db.get("SELECT * FROM ai_reports WHERE id = ? AND workspace_id = ?", [String(formData.get("id")), ws.id]);
  const path = `/app/${slug}/ai/reports/${rep?.id || ""}`;
  if (!rep || (rep.visibility === "PRIVATE" && rep.created_by !== user.id)) back(`/app/${slug}/ai`, { err: "Report not found." });
  if (needEdit && rep.created_by !== user.id && !can(ws.role, "admin")) back(path, { err: "Only the report's author or an admin can change it." });
  return { ws, user, rep, path, slug };
}

export async function setVisibility(formData) {
  const { ws, user, rep, path } = await ownReport(formData);
  const v = formData.get("visibility") === "TEAM" ? "TEAM" : "PRIVATE";
  await db.batch([{ sql: "UPDATE ai_reports SET visibility = ?, updated_at = ? WHERE id = ?", args: [v, db.now(), rep.id] }, auditStmt(ws.id, user.id, "ai.report_visibility", "ai_report", rep.id, { visibility: v })]);
  back(path, { ok: v === "TEAM" ? "Shared with everyone in this workspace." : "Now private to you." });
}

/** Create a read-only external link (token stored hashed; shown once). */
export async function createShareLink(formData) {
  const { ws, user, rep, path } = await ownReport(formData);
  if (!can(ws.role, "data.edit")) back(path, { err: "Your role can't share reports outside the workspace." });
  const days = Math.min(30, Math.max(1, parseInt(formData.get("days"), 10) || 7));
  const token = randomToken(24);
  const expires = new Date(Date.now() + days * 86400000).toISOString();
  await db.batch([{ sql: "UPDATE ai_reports SET share_token = ?, share_expires_at = ?, updated_at = ? WHERE id = ?", args: [sha256(token), expires, db.now(), rep.id] }, auditStmt(ws.id, user.id, "ai.report_link_created", "ai_report", rep.id, { days })]);
  redirect(`${path}?link=${encodeURIComponent(token)}&ok=${encodeURIComponent(`Share link created; it expires in ${days} day(s).`)}`);
}

export async function revokeShareLink(formData) {
  const { ws, user, rep, path } = await ownReport(formData);
  await db.batch([{ sql: "UPDATE ai_reports SET share_token = NULL, share_expires_at = NULL, updated_at = ? WHERE id = ?", args: [db.now(), rep.id] }, auditStmt(ws.id, user.id, "ai.report_link_revoked", "ai_report", rep.id, {})]);
  back(path, { ok: "Share link revoked." });
}

export async function deleteReport(formData) {
  const { ws, user, rep, slug } = await ownReport(formData);
  await db.batch([{ sql: "DELETE FROM ai_reports WHERE id = ?", args: [rep.id] }, auditStmt(ws.id, user.id, "ai.report_deleted", "ai_report", rep.id, { title: rep.title })]);
  back(`/app/${slug}/ai`, { ok: `Deleted “${rep.title}”.` });
}

export async function setAiConsent(formData) {
  const slug = String(formData.get("slug"));
  const { ws, user } = await requireWorkspace(slug, "OWNER");
  const consent = formData.get("consent") === "1";
  await setConsent(ws.id, consent, user.id);
  await db.batch([auditStmt(ws.id, user.id, consent ? "ai.consent_given" : "ai.consent_withdrawn", "workspace", ws.id, {})]);
  back(`/app/${slug}/settings#ai`, { ok: consent ? "AI is allowed for this company." : "Consent withdrawn. AI is off for this company." });
}

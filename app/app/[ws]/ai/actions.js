const AI_RATE = { limit: 20, windowMs: 60_000 };

/** Chat with the assistant (called from the floating panel and the AI page). */
export async function ask(slug, { conversationId, message, page, agentId, period, entityId } = {}) {
  const { ws, user } = await requireWorkspace(slug);
  if (!hit(AI_RATE, `ai|${user.id}`).ok) return { error: "You're sending questions very quickly. Wait a moment and try again." };
  return askAssistant({ ws, user, conversationId: conversationId || null, message, page, agentId: agentId ? String(agentId) : null, period: period ? String(period) : null, entityId: entityId ? String(entityId) : null });
}


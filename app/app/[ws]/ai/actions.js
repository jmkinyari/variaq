/** Queue a heavy specialist task (report, audit pack, tax recon, close summary) for the background worker. */
export async function enqueueAgentTask(slug, { agentId, kind, period, periodFrom, periodTo, entityId, title, instructions, template, withReport } = {}) {
  const { ws, user } = await requireWorkspace(slug);
  if (!hit("heavy", `ai-agent-job|${ws.id}`).ok) return { error: "Too many background tasks queued. Wait a minute." };
  const b = buildAgentPayload({ ws, user, agentId: String(agentId || ""), kind, period, periodFrom, periodTo, entityId, title, instructions, template, withReport });
  if (b.error) return { error: b.error };
  const r = await enqueueAgentJob(b.agent.id, b.payload, { createdBy: user.id });
  await db.batch([auditStmt(ws.id, user.id, "ai.agent_job_queued", "job", r.id, { agent: b.agent.id, kind: b.payload.kind, period: b.payload.periodFrom, deduped: !!r.deduped })]);
  return { ok: true, jobId: r.id, deduped: !!r.deduped, agentId: b.agent.id };
}


/** Form version (module pages / AI page): queue then come back with a flash message. */
export async function enqueueAgentTaskForm(formData) {
  const slug = String(formData.get("slug"));
  const backTo = String(formData.get("back") || `/app/${slug}/ai`);
  const safeBack = backTo.startsWith(`/app/${slug}`) ? backTo : `/app/${slug}/ai`;
  const r = await enqueueAgentTask(slug, Object.fromEntries(["agentId", "kind", "period", "periodFrom", "periodTo", "entityId", "title", "instructions", "template"].map((k) => [k, formData.get(k) ? String(formData.get(k)) : undefined])));
  if (r.error) back(safeBack, { err: r.error });
  back(safeBack, { ok: r.deduped ? "That task is already queued — it will appear under Artifacts when ready." : "Queued in the background. The result will appear under Artifacts on the AI page." });
}

